#!/usr/bin/env python3
"""Render launcher and web icons from web/public/icons/wt.svg.

Run: python3 -m pip install -r scripts/icon-requirements.txt
     python3 scripts/generate-icons.py
     python3 scripts/generate-icons.py --check

No SVG renderer is required: Pillow draws the source rectangle and two polygons
at 4x resolution, then downsamples with Lanczos. This intentionally supports only
the existing mark's simple SVG vocabulary and fails on unsupported artwork.
Pillow is pinned so PNG/ICO encoding and rasterization stay reproducible.
Android maps the SVG viewBox to the central 66dp of its 108dp canvas; the
monochrome layer uses the same geometry with a solid themeable alpha mask.
The SVG, iOS assets and HTML templates are never modified.
"""

import argparse
from io import BytesIO
from pathlib import Path
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
ANDROID = Path("mobile/android/app/src/main/res")
NS = "http://www.w3.org/2000/svg"


def artwork():
    svg = ET.parse(ROOT / "web/public/icons/wt.svg").getroot()
    x, y, width, height = map(float, svg.attrib["viewBox"].split())
    if width != height or [el.tag for el in svg] != [
        f"{{{NS}}}rect", f"{{{NS}}}polygon", f"{{{NS}}}polygon"
    ]:
        raise ValueError("Expected the wt square viewBox, rectangle and two polygons")
    background = svg[0].attrib["fill"]
    if any(key not in {"width", "height", "fill"} for key in svg[0].attrib):
        raise ValueError("Unsupported rectangle attributes")
    if float(svg[0].attrib["width"]) < x + width or float(svg[0].attrib["height"]) < y + height:
        raise ValueError("Background must cover the viewBox")
    polygons = []
    for el in svg[1:]:
        if set(el.attrib) != {"fill", "points"}:
            raise ValueError("Unsupported polygon attributes")
        points = [tuple(map(float, pair.split(","))) for pair in el.attrib["points"].split()]
        polygons.append((el.attrib["fill"], points))
    return (x, y, width), background, polygons


def render(size, art):
    (x, y, width), background, polygons = art
    image = Image.new("RGB", (size * 4, size * 4), background)
    draw = ImageDraw.Draw(image)
    scale = size * 4 / width
    for color, points in polygons:
        draw.polygon([((px - x) * scale, (py - y) * scale) for px, py in points], fill=color)
    return image.resize((size, size), Image.Resampling.LANCZOS)


def vector(art, monochrome=False):
    (x, y, width), _, polygons = art
    scale = 66 / width
    paths = []
    for color, points in polygons:
        path = "M" + "L".join(f"{px:g},{py:g}" for px, py in points) + "z"
        paths.append(f'  <path android:fillColor="{"#FFFFFF" if monochrome else color}" android:pathData="{path}" />')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by scripts/generate-icons.py from wt.svg. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            ' android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            f' <group android:scaleX="{scale:.12f}" android:scaleY="{scale:.12f}" '
            f'android:translateX="{21 - x * scale:.12f}" android:translateY="{21 - y * scale:.12f}">\n'
            + "\n".join(paths) + '\n </group>\n</vector>\n').encode()


def outputs():
    art = artwork()
    result = {}
    for size in (180, 192, 512):
        buffer = BytesIO()
        render(size, art).save(buffer, format="PNG", optimize=False, compress_level=9)
        result[Path(f"web/public/icons/wt-{size}.png")] = buffer.getvalue()
    sizes = (16, 29, 32, 48, 64)
    buffer = BytesIO()
    # Supply every size explicitly: each frame gets its own 4x rendering.
    render(64, art).save(buffer, format="ICO", sizes=[(n, n) for n in sizes],
                         append_images=[render(n, art) for n in sizes if n != 64])
    result[Path("web/public/favicon.ico")] = buffer.getvalue()
    result[ANDROID / "drawable/ic_launcher_foreground.xml"] = vector(art)
    result[ANDROID / "drawable/ic_launcher_monochrome.xml"] = vector(art, monochrome=True)
    result[ANDROID / "drawable/ic_launcher_background.xml"] = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by scripts/generate-icons.py from wt.svg. -->\n'
        '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">\n'
        f' <solid android:color="{art[1]}" />\n</shape>\n').encode()
    result[ANDROID / "mipmap-anydpi-v26/ic_launcher.xml"] = b'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-icons.py from wt.svg. Min SDK is 26. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
 <background android:drawable="@drawable/ic_launcher_background" />
 <foreground android:drawable="@drawable/ic_launcher_foreground" />
 <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="check bytes without writing")
    group.add_argument("--output-dir", type=Path, help="write generated tree under another directory")
    args = parser.parse_args()
    root = args.output_dir or ROOT
    stale = []
    for path, content in outputs().items():
        target = root / path
        if args.check:
            if not target.exists() or target.read_bytes() != content:
                stale.append(str(path))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        print(path)
    if stale:
        parser.exit(1, "Stale icons: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
